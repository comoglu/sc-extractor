def export_to_sqlite(
    results: List[Dict],
    output_path: str | Path,
    selected_fields: List[str],
) -> Path:
    """
    Write records to a SQLite database with two tables:
      events   — one row per event (event-level fields)
      arrivals — one row per arrival (all other selected fields + event_id FK)
    """
    import sqlite3

    output_path = Path(output_path)

    ev_fields  = [f for f in selected_fields if f in _EVENT_LEVEL_FIELDS]
    arr_fields = [f for f in selected_fields if f not in _EVENT_LEVEL_FIELDS]

    def _col_type(f: str) -> str:
        # Numeric fields get REAL, everything else TEXT
        _numeric = {
            "event_timestamp", "event_latitude", "event_longitude", "event_depth",
            "event_depth_uncertainty", "event_latitude_uncertainty",
            "event_longitude_uncertainty", "event_magnitude_value",
            "event_magnitude_uncertainty", "event_magnitude_station_count",
            "event_magnitude_azimuthal_gap", "location_quality_score",
            "origin_quality_standard_error", "origin_quality_azimuthal_gap",
            "origin_quality_used_phase_count", "origin_quality_used_station_count",
            "origin_quality_minimum_distance", "origin_quality_maximum_distance",
            "arrival_distance", "distance_km", "arrival_azimuth",
            "arrival_residual", "arrival_weight",
            "travel_time_p", "travel_time_s",
            "sp_time", "sp_time_used_only",
            "vp_estimate", "vs_estimate", "vp_vs_ratio",
            "station_latitude", "station_longitude", "station_elevation",
            "station_magnitude_value", "station_magnitude_uncertainty",
            "station_magnitude_residual",
        }
        return "REAL" if f in _numeric else "TEXT"

    with sqlite3.connect(output_path) as conn:
        cur = conn.cursor()
        cur.execute("DROP TABLE IF EXISTS arrivals")
        cur.execute("DROP TABLE IF EXISTS events")

        ev_col_defs = ", ".join(f'"{f}" {_col_type(f)}' for f in ev_fields)
        cur.execute(f"""CREATE TABLE events (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            event_id TEXT NOT NULL UNIQUE
            {(',' + ev_col_defs) if ev_col_defs else ''}
        )""")

        arr_col_defs = ", ".join(f'"{f}" {_col_type(f)}' for f in arr_fields)
        cur.execute(f"""CREATE TABLE arrivals (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            event_id TEXT NOT NULL REFERENCES events(event_id)
            {(',' + arr_col_defs) if arr_col_defs else ''}
        )""")

        seen: set[str] = set()
        for result in results:
            eid = result.get("eventId", "unknown")
            records = result.get("records", [])
            if not records:
                continue
            ref = records[0]

            if eid not in seen:
                if ev_fields:
                    vals = [ref.get(f) for f in ev_fields]
                    ph   = ",".join("?" * len(ev_fields))
                    cols = ",".join(f'"{f}"' for f in ev_fields)
                    cur.execute(
                        f'INSERT INTO events (event_id,{cols}) VALUES (?,{ph})',
                        [eid] + vals,
                    )
                else:
                    cur.execute('INSERT INTO events (event_id) VALUES (?)', [eid])
                seen.add(eid)

            for rec in records:
                if arr_fields:
                    vals = [rec.get(f) for f in arr_fields]
                    ph   = ",".join("?" * len(arr_fields))
                    cols = ",".join(f'"{f}"' for f in arr_fields)
                    cur.execute(
                        f'INSERT INTO arrivals (event_id,{cols}) VALUES (?,{ph})',
                        [eid] + vals,
                    )
                else:
                    cur.execute('INSERT INTO arrivals (event_id) VALUES (?)', [eid])

        conn.commit()

    return output_path


