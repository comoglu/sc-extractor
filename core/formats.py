def export_to_parquet(
    results: List[Dict],
    output_path: str | Path,
    selected_fields: List[str],
) -> Path:
    """
    Write all records to a single Parquet file.
    Requires: pyarrow  (pip install pyarrow)
    """
    try:
        import pyarrow as pa
        import pyarrow.parquet as pq
    except ImportError as exc:
        raise ImportError(
            "Parquet export requires pyarrow. Install with: pip install pyarrow"
        ) from exc

    output_path = Path(output_path)
    rows: list[dict] = []

    for result in results:
        eid = result.get("eventId", "unknown")
        for rec in result.get("records", []):
            row = {"_event_id": eid}
            for f in selected_fields:
                row[f] = rec.get(f)
            rows.append(row)

    all_cols = ["_event_id"] + selected_fields

    if not rows:
        table = pa.table({c: pa.array([], type=pa.string()) for c in all_cols})
    else:
        col_data: dict[str, list] = {c: [] for c in all_cols}
        for row in rows:
            for c in all_cols:
                col_data[c].append(row.get(c))
        table = pa.table(col_data)

    pq.write_table(table, output_path, compression="snappy")
    return output_path
